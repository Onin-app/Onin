//! 自动将 Rust 核心数据结构导出为 TypeScript 类型定义

use specta::Types;
use specta_typescript::Typescript;
use std::path::Path;

/// 收集所有核心领域模型的类型定义
pub fn collect_types() -> Types {
    Types::default()
        // shared_types
        .register::<crate::shared_types::ItemSource>()
        .register::<crate::shared_types::CommandType>()
        .register::<crate::shared_types::ItemType>()
        .register::<crate::shared_types::IconType>()
        .register::<crate::shared_types::AppOrigin>()
        .register::<crate::shared_types::LaunchableItem>()
        .register::<crate::shared_types::CommandMatch>()
        .register::<crate::shared_types::CommandKeyword>()
        .register::<crate::shared_types::CommandAction>()
        .register::<crate::shared_types::Command>()
        .register::<crate::shared_types::Shortcut>()
        .register::<crate::shared_types::PluginCommand>()
        .register::<crate::shared_types::CommandResult>()
        .register::<crate::shared_types::DynamicCommand>()
        // app_config
        .register::<crate::app_config::SortMode>()
        .register::<crate::app_config::LauncherMode>()
        .register::<crate::app_config::WebDavConfig>()
        .register::<crate::app_config::AppConfig>()
        // usage_tracker
        .register::<crate::usage_tracker::CommandUsageStats>()
}

/// 导出 TypeScript 文件至指定路径
pub fn export_to_file<P: AsRef<Path>>(path: P) -> Result<(), specta_typescript::Error> {
    let types = collect_types();
    Typescript::default()
        .header("// This file was generated by Specta. DO NOT EDIT DIRECTLY.\n/* eslint-disable */\n// @ts-nocheck\n")
        .export_to(path, &types, specta_serde::Format)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_export_types() {
        let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".to_string());
        let target_path = std::path::Path::new(&manifest_dir).join("../src/lib/types/bindings.ts");

        export_to_file(&target_path).expect("Failed to export TypeScript types");
        println!("[specta] Successfully exported types to {:?}", target_path);
    }
}
